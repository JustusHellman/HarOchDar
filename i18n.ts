export const getInitialLanguage = (): Language => {
  try {
    const saved = localStorage.getItem("locateit_language");
    if (saved === "en" || saved === "sv") return saved;
    const browserLang = navigator.language || (navigator.languages && navigator.languages[0]) || "";
    if (browserLang.toLowerCase().startsWith("sv")) {
      return "sv";
    }
  } catch {
    // fallback
  }
  return "en";
};

let currentLanguage: Language = typeof window !== "undefined" ? getInitialLanguage() : "en";

export const getLanguage = (): Language => currentLanguage;

export const setLanguageGlobal = (lang: Language) => {
  currentLanguage = lang;
  try {
    localStorage.setItem("locateit_language", lang);
  } catch {}
  if (typeof document !== "undefined") {
    document.title = lang === "sv" ? "Här & Där - Anpassat Kartquiz" : "Here & There - Custom Map Quiz";
  }
};

interface I18nContextType {
  language: Language;
  setLanguage: (lang: Language) => void;
  toggleLanguage: () => void;
  strings: TranslationSchema;
}

const I18nContext = createContext<I18nContextType>({
  language: currentLanguage,
  setLanguage: () => {},
  toggleLanguage: () => {},
  strings: currentLanguage === "sv" ? svStrings : enStrings,
});

export const I18nProvider: React.FC<{ children: ReactNode }> = ({ children }) => {
  const [language, setLanguageState] = useState<Language>(getInitialLanguage);

  const setLanguage = (lang: Language) => {
    setLanguageState(lang);
    setLanguageGlobal(lang);
  };

  const toggleLanguage = () => {
    setLanguage(language === "sv" ? "en" : "sv");
  };

  useEffect(() => {
    setLanguageGlobal(language);
  }, [language]);

  const activeStrings = language === "sv" ? svStrings : enStrings;

  return React.createElement(
    I18nContext.Provider,
    { value: { language, setLanguage, toggleLanguage, strings: activeStrings } },
    children
  );
};

export const useI18n = () => useContext(I18nContext);
export const useLanguage = useI18n;

export const strings: TranslationSchema = new Proxy({} as TranslationSchema, {
  get(_target, prop: string) {
    const active = currentLanguage === "sv" ? svStrings : enStrings;
    return (active as any)[prop];
  },
});
